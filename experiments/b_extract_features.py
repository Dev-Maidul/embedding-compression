"""Extract and cache all three Part B feature types for the full 10,000
CIFAR-10 test images: raw pixels, HOG, and pretrained ResNet-18
penultimate features. Writes .npy files to data/features/ (gitignored --
these are regenerated by this script, not stored in the repo) and a short
timing/shape summary to results/b_feature_extraction.csv.
"""

import os
import time

import numpy as np
import pandas as pd

from src.features.cifar_loader import load_cifar10_test
from src.features.hog import extract_hog_features
from src.features.pixels import extract_pixel_features
from src.features.resnet import extract_resnet_features, load_resnet18_feature_extractor

SEED = 42
RESNET_RESOLUTION = 224  # see results/b_resnet_resolution_benchmark.csv and docs/DECISIONS.md
RESNET_BATCH_SIZE = 64
OUT_DIR = "data/features"


def main():
    np.random.seed(SEED)
    os.makedirs(OUT_DIR, exist_ok=True)

    print("Loading CIFAR-10 test set...")
    images, labels = load_cifar10_test()
    n = images.shape[0]
    print(f"Loaded {n} images, shape {images.shape}, labels shape {labels.shape}")

    np.save(os.path.join(OUT_DIR, "labels.npy"), labels)

    rows = []

    print("Extracting raw pixel features...")
    t0 = time.perf_counter()
    pixel_feats = extract_pixel_features(images)
    t_pixels = time.perf_counter() - t0
    np.save(os.path.join(OUT_DIR, "pixels.npy"), pixel_feats)
    rows.append({"feature": "pixels", "shape": str(pixel_feats.shape), "elapsed_sec": t_pixels})
    print(f"  pixels: shape={pixel_feats.shape}, {t_pixels:.1f}s")

    print("Extracting HOG features...")
    t0 = time.perf_counter()
    hog_feats = extract_hog_features(images)
    t_hog = time.perf_counter() - t0
    np.save(os.path.join(OUT_DIR, "hog.npy"), hog_feats)
    rows.append({"feature": "hog", "shape": str(hog_feats.shape), "elapsed_sec": t_hog})
    print(f"  hog: shape={hog_feats.shape}, {t_hog:.1f}s")

    print(f"Extracting ResNet-18 features (resolution={RESNET_RESOLUTION})...")
    model = load_resnet18_feature_extractor()
    t0 = time.perf_counter()
    resnet_feats = extract_resnet_features(
        images, model, resolution=RESNET_RESOLUTION, batch_size=RESNET_BATCH_SIZE
    )
    t_resnet = time.perf_counter() - t0
    np.save(os.path.join(OUT_DIR, "resnet.npy"), resnet_feats)
    rows.append({"feature": "resnet", "shape": str(resnet_feats.shape), "elapsed_sec": t_resnet})
    print(f"  resnet: shape={resnet_feats.shape}, {t_resnet:.1f}s")

    df = pd.DataFrame(rows)
    df.to_csv("results/b_feature_extraction.csv", index=False)
    print(f"\nWrote results/b_feature_extraction.csv")
    print(f"Cached .npy files in {OUT_DIR}/ (gitignored)")


if __name__ == "__main__":
    main()
